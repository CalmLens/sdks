// Command errorcodesgen writes errorcodes.go from packages/shared/src/PublicErrorCodes.ts.
// Run it with go generate ./... from go.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

var entry = regexp.MustCompile(`(?s)\n  ([A-Z0-9_]+): new ErrorCode\(\{\s*id: ("[^"]+"|[A-Z][A-Z0-9_]*),.*?status: (\d+),`)
var stringConstant = regexp.MustCompile(`(?m)^export const ([A-Z][A-Z0-9_]*) = ("[^"]+");$`)
var relativeImport = regexp.MustCompile(`(?m)^import [^\n]+ from "\./([A-Za-z0-9]+)";$`)

func generateFile(path string) ([]byte, error) {
	source, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var imports [][]byte
	for _, match := range relativeImport.FindAllSubmatch(source, -1) {
		imported, err := os.ReadFile(filepath.Join(filepath.Dir(path), string(match[1])+".ts"))
		if err != nil {
			return nil, err
		}
		imports = append(imports, imported)
	}
	return generate(source, imports...)
}

// generate returns the Go source for the error codes declared in source.
func generate(source []byte, imports ...[]byte) ([]byte, error) {
	matches := entry.FindAllSubmatch(source, -1)
	if len(matches) == 0 {
		return nil, fmt.Errorf("no error codes found")
	}
	constants := make(map[string]string)
	for _, dependency := range imports {
		for _, match := range stringConstant.FindAllSubmatch(dependency, -1) {
			constants[string(match[1])] = string(match[2])
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/errorcodesgen from packages/shared/src/PublicErrorCodes.ts. DO NOT EDIT.\n\npackage calmlens\n\n")
	out.WriteString("// Error codes the CalmLens API returns in Error.Code. Compare against these constants\n// rather than string literals; new codes may be added at any time.\nconst (\n")
	for _, m := range matches {
		value := string(m[2])
		if !strings.HasPrefix(value, `"`) {
			value = constants[value]
		}
		code, err := strconv.Unquote(value)
		if err != nil {
			return nil, fmt.Errorf("cannot resolve error code %s: %s", m[1], m[2])
		}
		fmt.Fprintf(&out, "\t// %s is returned with HTTP %s.\n\t%s ErrorCode = %q\n", name(string(m[1])), m[3], name(string(m[1])), code)
	}
	out.WriteString(")\n\nvar publicErrorStatuses = map[ErrorCode]int{\n")
	for _, m := range matches {
		fmt.Fprintf(&out, "\t%s: %s,\n", name(string(m[1])), m[3])
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

// name turns ASSET_NOT_FOUND into CodeAssetNotFound.
func name(key string) string {
	var out strings.Builder
	out.WriteString("Code")
	for _, word := range strings.Split(key, "_") {
		switch word {
		case "API", "URL", "ID", "CSAM", "CDN":
			out.WriteString(word)
		default:
			out.WriteString(word[:1] + strings.ToLower(word[1:]))
		}
	}
	return out.String()
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: errorcodesgen <PublicErrorCodes.ts> <errorcodes.go>")
		os.Exit(2)
	}
	generated, err := generateFile(os.Args[1])
	if err == nil {
		err = os.WriteFile(os.Args[2], generated, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
