// Command errorcodesgen writes errorcodes.go from packages/shared/src/PublicErrorCodes.ts.
// Run it with go generate ./... from go.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

var entry = regexp.MustCompile(`(?s)\n  ([A-Z0-9_]+): new ErrorCode\(\{\s*id: "([^"]+)",.*?status: (\d+),`)

// generate returns the Go source for the error codes declared in source.
func generate(source []byte) ([]byte, error) {
	matches := entry.FindAllSubmatch(source, -1)
	if len(matches) == 0 {
		return nil, fmt.Errorf("no error codes found")
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/errorcodesgen from packages/shared/src/PublicErrorCodes.ts. DO NOT EDIT.\n\npackage calmlens\n\n")
	out.WriteString("// Error codes the CalmLens API returns in Error.Code. Compare against these constants\n// rather than string literals; new codes may be added at any time.\nconst (\n")
	for _, m := range matches {
		fmt.Fprintf(&out, "\t// %s is returned with HTTP %s.\n\t%s = %q\n", name(string(m[1])), m[3], name(string(m[1])), m[2])
	}
	out.WriteString(")\n\nvar publicErrorStatuses = map[string]int{\n")
	for _, m := range matches {
		fmt.Fprintf(&out, "\t%s: %s,\n", name(string(m[1])), m[3])
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

// name turns ASSET_NOT_FOUND into CodeAssetNotFound.
func name(key string) string {
	var out strings.Builder
	out.WriteString("Code")
	for _, word := range strings.Split(key, "_") {
		switch word {
		case "API", "URL", "ID", "CSAM", "CDN":
			out.WriteString(word)
		default:
			out.WriteString(word[:1] + strings.ToLower(word[1:]))
		}
	}
	return out.String()
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: errorcodesgen <PublicErrorCodes.ts> <errorcodes.go>")
		os.Exit(2)
	}
	source, err := os.ReadFile(os.Args[1])
	if err == nil {
		var generated []byte
		if generated, err = generate(source); err == nil {
			err = os.WriteFile(os.Args[2], generated, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
