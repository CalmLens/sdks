// Writes src/client/CalmLensErrorCodes.ts from shared/PublicErrorCodes, so the SDK exports the
// API's error codes as plain strings without bundling the server's error classes.
// Run after changing PublicErrorCodes: bun packages/js-sdk/scripts/generate-error-codes.ts
import { PUBLIC_ERROR_CODES } from "../src/contract/PublicErrorCodes.js";

export const OUTPUT_PATH = new URL("../src/client/CalmLensErrorCodes.ts", import.meta.url);

export const renderErrorCodes = (): string => {
  const entries = Object.entries(PUBLIC_ERROR_CODES).map(([name, code]) => ({
    name,
    id: code.getId(),
    status: code.getStatus(),
    message: code.getDefaultMessage(),
  }));
  return [
    "// Generated by scripts/generate-error-codes.ts from shared/PublicErrorCodes. Do not edit.",
    "",
    "/** Error codes the CalmLens API documents, by name. */",
    "export const API_ERROR_CODES = {",
    ...entries.map(({ name, id }) => `  ${name}: ${JSON.stringify(id)},`),
    "} as const;",
    "",
    "export type ApiErrorCode = (typeof API_ERROR_CODES)[keyof typeof API_ERROR_CODES];",
    "",
    "export interface ApiErrorDefinition {",
    "  status: number;",
    "  message: string;",
    "}",
    "",
    "/** The HTTP status and default message the API returns with each documented error code. */",
    "export const API_ERROR_DEFINITIONS: Record<ApiErrorCode, ApiErrorDefinition> = {",
    ...entries.map(({ id, status, message }) =>
      [
        `  ${JSON.stringify(id)}: {`,
        `    status: ${status},`,
        `    message: ${JSON.stringify(message)},`,
        "  },",
      ].join("\n"),
    ),
    "};",
    "",
  ].join("\n");
};

if (import.meta.main) {
  await Bun.write(OUTPUT_PATH, renderErrorCodes());
}
